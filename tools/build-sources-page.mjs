#!/usr/bin/env node
/**
 * Generates docs/sources.html: every chapter's "Sources and further reading"
 * list, in book order, on one reference page.
 *
 * The chapters stay the single source of truth: this tool copies each
 * chapter's <section class="sources"> list items verbatim. The structure
 * tests fail if the generated page is stale.
 *
 * Usage: npm run build:sources      (LOG_LEVEL=debug for detail)
 */
import { writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { DOCS, loadData, readPage } from "./lib/site.mjs";
import { logger } from "./lib/log.mjs";

const log = logger("sources-page");
const OUT = join(DOCS, "sources.html");

/** Inner HTML of a chapter's sources list (its <li> items), or "". */
function sourceItems(html) {
  const section = html.match(/<section class="sources" id="sources"[^>]*>([\s\S]*?)<\/section>/);
  if (!section) return "";
  const list = section[1].match(/<ul>([\s\S]*)<\/ul>/);
  return list ? list[1].trim() : "";
}

function escapeHtml(text) {
  return text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

/** Builds the full page. Exported so the tests can compare it to disk. */
export function buildSourcesPage() {
  const { nav } = loadData();
  const blocks = [];
  let chapters = 0;
  let items = 0;
  for (const part of nav.parts) {
    const written = part.chapters.filter((c) => c.status === "published" && existsSync(join(DOCS, c.file)));
    if (!written.length) continue;
    const chapterBlocks = written.map((ch) => {
      const inner = sourceItems(readPage(ch.file));
      if (!inner) {
        log.warn(`${ch.file} has no sources list`);
        return "";
      }
      chapters++;
      items += (inner.match(/<li\b/g) || []).length;
      const id = `src-${ch.num.replace(".", "-")}`;
      return [
        `          <section class="sources-chapter" id="${id}" aria-labelledby="${id}-t">`,
        `            <h3 id="${id}-t"><a href="${ch.file}">${ch.num} ${escapeHtml(ch.title)}</a></h3>`,
        `            <ul>`,
        `              ${inner}`,
        `            </ul>`,
        `          </section>`,
      ].join("\n");
    });
    blocks.push([
      `        <section class="section" aria-labelledby="part-${part.n}">`,
      `          <h2 id="part-${part.n}">Part ${part.n} · ${escapeHtml(part.title)}</h2>`,
      chapterBlocks.filter(Boolean).join("\n"),
      `        </section>`,
    ].join("\n"));
  }

  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
  <title>Sources and further reading · Graphics Handbook</title>
  <meta name="description" content="Every paper, talk and documentation page the Graphics Handbook cites, grouped by chapter.">
  <script src="assets/js/theme-init.js"></script>
  <link rel="stylesheet" href="assets/css/tokens.css">
  <link rel="stylesheet" href="assets/css/site.css">
  <link rel="stylesheet" href="assets/css/diagrams.css">
</head>
<body data-page="sources">
  <!-- GENERATED by tools/build-sources-page.mjs from each chapter's sources
       section. Do not edit by hand: edit the chapter, then run
       npm run build:sources. -->
  <a class="skip-link" href="#main">Skip to content</a>
  <header class="site-header">
    <a class="brand" href="index.html">
      <svg class="brand-mark" viewBox="0 0 24 24" aria-hidden="true"><path class="tri" d="M4 19.5L12 4.5L20 19.5Z"/><circle class="dot" cx="20" cy="19.5" r="2.6"/></svg>
      Graphics Handbook
    </a>
    <div class="header-tools" id="header-tools"></div>
  </header>

  <div class="layout">
    <nav class="sidebar" id="sidebar" aria-label="Chapters"></nav>
    <main id="main" class="main">
      <div class="content home">
        <section class="hero" aria-labelledby="sources-title">
          <p class="eyebrow">Reference</p>
          <h1 id="sources-title">Sources and further reading</h1>
          <p class="lead">Every paper, conference talk and documentation page the chapters cite, grouped by chapter: ${items} sources across ${chapters} chapters. Engine documentation changes between versions; each chapter's engine table states which versions were checked.</p>
        </section>
${blocks.join("\n")}
      </div>
    </main>
  </div>
  <footer class="site-footer" id="site-footer"></footer>

  <script src="assets/js/log.js"></script>
  <script src="assets/js/data/nav.js"></script>
  <script src="assets/js/data/glossary.js"></script>
  <script src="assets/js/data/search-index.js"></script>
  <script src="assets/js/shell.js"></script>
</body>
</html>
`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(OUT, buildSourcesPage());
  log.info(`wrote ${OUT}`);
}
